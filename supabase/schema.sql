create or replace view public.v_lotes_inventario as
select
  l.id,
  l.codigo_lote,
  l.cantidad,
  l.fecha_vencimiento,
  l.precio_compra,
  l.activo,
  p.codigo as producto_codigo,
  p.nombre as producto_nombre,
  p.stock_minimo,
  c.nombre as categoria_nombre,
  pr.nombre as proveedor_nombre,
  case
    when l.fecha_vencimiento <= current_date + interval '30 days' then 'Por vencer'
    when l.cantidad <= p.stock_minimo then 'Stock bajo'
    else 'Disponible'
  end as estado_lote
from public.lotes l
join public.productos p on p.id = l.producto_id
left join public.categorias c on c.id = p.categoria_id
left join public.proveedores pr on pr.id = l.proveedor_id;

