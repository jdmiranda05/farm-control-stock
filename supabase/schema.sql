-- Botica M&LL
-- Base de datos para las pantallas: Login, Dashboard de Almacen,
-- Inventario/Lotes y Kardex de Entrada.
-- Entidad nucleo: lote.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombres text not null,
  apellidos text not null,
  rol text not null default 'almacen',
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create table if not exists public.categorias (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create table if not exists public.proveedores (
  id bigint generated by default as identity primary key,
  nombre text not null,
  ruc varchar(11) unique,
  telefono text,
  email text,
  direccion text,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  categoria_id bigint references public.categorias(id) on update cascade on delete restrict,
  codigo text not null unique,
  nombre text not null,
  principio_activo text,
  concentracion text,
  presentacion text not null,
  unidad_medida text not null default 'unidad',
  stock_minimo integer not null default 0 check (stock_minimo >= 0),
  precio_venta numeric(10,2) not null default 0 check (precio_venta >= 0),
  requiere_receta boolean not null default false,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create table if not exists public.lotes (
  id bigint generated by default as identity primary key,
  producto_id bigint not null references public.productos(id) on update cascade on delete restrict,
  proveedor_id bigint references public.proveedores(id) on update cascade on delete set null,
  codigo_lote text not null unique,
  cantidad integer not null check (cantidad >= 0),
  fecha_vencimiento date not null,
  precio_compra numeric(10,2) not null default 0 check (precio_compra >= 0),
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists public.movimientos_kardex (
  id bigint generated by default as identity primary key,
  producto_id bigint references public.productos(id) on update cascade on delete set null,
  lote_id bigint references public.lotes(id) on update cascade on delete set null,
  usuario_id uuid references public.profiles(id) on update cascade on delete set null,
  tipo text not null check (tipo in ('entrada', 'salida', 'ajuste')),
  cantidad integer not null check (cantidad > 0),
  motivo text not null,
  costo_unitario numeric(10,2) not null default 0 check (costo_unitario >= 0),
  fecha timestamptz not null default now()
);

create or replace function public.set_actualizado_en()
returns trigger
language plpgsql
as $$
begin
  new.actualizado_en = now();
  return new;
end;
$$;

drop trigger if exists trg_lotes_actualizado_en on public.lotes;
create trigger trg_lotes_actualizado_en
before update on public.lotes
for each row
execute function public.set_actualizado_en();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, nombres, apellidos, rol)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nombres', 'Usuario'),
    coalesce(new.raw_user_meta_data->>'apellidos', 'M&LL'),
    coalesce(new.raw_user_meta_data->>'rol', 'almacen')
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row
execute function public.handle_new_user();

